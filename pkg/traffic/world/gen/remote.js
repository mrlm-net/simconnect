// Generates pkg/traffic/world/remote_gen.go: the director's stand-ins for the
// actuator's objects, one method per interface method, each a wire call.
const fs = require('fs');
const dir = process.argv[2];
function ifaceMethods(file, name) {
  const s = fs.readFileSync(dir + '/' + file, 'utf8').split('\r\n').join('\n');
  const i = s.indexOf('type ' + name + ' interface {');
  if (i < 0) throw 'no ' + name;
  const body = s.slice(s.indexOf('{', i) + 1, s.indexOf('\n}', i));
  return body.split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('//'));
}
function splitTop(s) { // split by commas at depth 0
  const out = []; let d = 0, cur = '';
  for (const ch of s) {
    if ('([{'.includes(ch)) d++; if (')]}'.includes(ch)) d--;
    if (ch === ',' && d === 0) { out.push(cur.trim()); cur = ''; } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}
function parse(line) {
  const name = line.slice(0, line.indexOf('('));
  let d = 0, j = line.indexOf('(');
  for (let k = j; k < line.length; k++) { if (line[k] === '(') d++; if (line[k] === ')') { d--; if (d === 0) { j = k; break; } } }
  const params = line.slice(line.indexOf('(') + 1, j).trim();
  let res = line.slice(j + 1).trim();
  if (res.startsWith('(')) res = res.slice(1, -1);
  // params: "a, b float64, c string" — names share the next type
  const ps = []; let pending = [];
  for (const p of splitTop(params)) {
    const sp = p.indexOf(' ');
    if (sp < 0) { pending.push(p); continue; }
    const n = p.slice(0, sp), t = p.slice(sp + 1).trim();
    for (const q of pending) ps.push([q, t]);
    pending = []; ps.push([n, t]);
  }
  const rs = res ? splitTop(res).map(r => { const sp = r.indexOf(' '); return sp > 0 && !r.startsWith('[') && !r.startsWith('*') && !r.startsWith('map') && /^[a-z]/.test(r) && r.split(' ').length === 2 ? r.split(' ')[1] : r; }) : [];
  return { name, ps, rs };
}
function stub(recv, m) {
  if (m.name === 'Handle') return `func (r *${recv}) Handle(msg engine.Message) bool { return false } // the actuator handles its messages\n`;
  const args = m.ps.map(p => p[0] + ' ' + p[1]).join(', ');
  const nonErr = m.rs.filter(t => t !== 'error');
  const hasErr = m.rs.includes('error');
  let b = '';
  nonErr.forEach((t, i) => { b += `\tvar o${i} ${t}\n`; });
  const call = `r.c.call(r.t, "${m.name}", []any{${m.ps.map(p => p[0]).join(', ')}}${nonErr.map((_, i) => ', &o' + i).join('')})`;
  if (hasErr) b += `\terr := ${call}\n`; else b += `\tr.c.dropped(${call})\n`;
  const rets = m.rs.map(t => t === 'error' ? 'err' : 'o' + nonErr.indexOf(t)); // types unique in our methods
  // results by position (two results of one type would need care)
  let k = 0; const rets2 = m.rs.map(t => t === 'error' ? 'err' : 'o' + (k++));
  if (m.rs.length) b += `\treturn ${rets2.join(', ')}\n`;
  const resSig = m.rs.length === 0 ? '' : m.rs.length === 1 ? ' ' + m.rs[0] : ' (' + m.rs.join(', ') + ')';
  return `func (r *${recv}) ${m.name}(${args})${resSig} {\n${b}}\n`;
}
let out = '// Code generated by gen/remote.js from controllers.go and sim.go; DO NOT EDIT.\n\npackage world\n\nimport (\n\t"time"\n\n\t"github.com/mrlm-net/simconnect/pkg/airport"\n\t"github.com/mrlm-net/simconnect/pkg/engine"\n\t"github.com/mrlm-net/simconnect/pkg/traffic"\n\t"github.com/mrlm-net/simconnect/pkg/types"\n)\n\n';
out += 'var (\n\t_ = time.Second\n\t_ airport.LatLon\n\t_ types.SIMCONNECT_DATA_WAYPOINT\n\t_ traffic.RoutePoint\n)\n\n';
for (const [file, iface, recv] of [['controllers.go', 'departureCtl', 'remoteDep'], ['controllers.go', 'arrivalCtl', 'remoteArr'], ['sim.go', 'simPort', 'remoteSim']]) {
  out += `// ${recv} is the director's ${iface}: each call a wire call.\n`;
  for (const l of ifaceMethods(file, iface)) {
    const m = parse(l);
    if (recv === 'remoteSim' && (m.name === 'StartDeparture' || m.name === 'StartArrival')) continue;
    out += stub(recv, m) + '\n';
  }
}
fs.writeFileSync(dir + '/remote_gen.go', out);
console.log('ok');
